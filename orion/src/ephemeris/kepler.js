const CW_LO = 2360234.5, CW_HI = 2542800.0, CFADE = 36525;
const smooth = (x) => { x = x < 0 ? 0 : x > 1 ? 1 : x; return x * x * (3 - 2 * x); };
function corrected(id, jd, out) {
  const c = CORR[id], T = (jd - 2451545.0) / 36525, Tc = T < -2.5 ? -2.5 : T > 2.5 ? 2.5 : T;
  const d = [0, 0, 0];
  for (let k = 0; k < 3; k++) { const p = c.poly[k]; d[k] = p[0] + Tc * (p[1] + Tc * (p[2] + Tc * p[3])); }
  const LJ = (34.39644051 + 3034.74612775 * T) * DEG, LS = (49.95424423 + 1222.49362201 * T) * DEG;
  for (const t of c.terms) {
    const a = t[0] * LJ + t[1] * LS, ca = Math.cos(a), sa = Math.sin(a);
    d[0] += t[2] * ca + t[3] * sa; d[1] += t[4] * ca + t[5] * sa; d[2] += t[6] * ca + t[7] * sa;
  }
  raw(id, jd, out, true);
  const r = Math.hypot(out[0], out[1], out[2]), lon = Math.atan2(out[1], out[0]) + d[0], lat = Math.asin(out[2] / r) + d[1];
  const rr = r * (1 + d[2]), cl = Math.cos(lat);
  out[0] = rr * cl * Math.cos(lon); out[1] = rr * cl * Math.sin(lon); out[2] = rr * Math.sin(lat);
  return out;
}

const tmpB = new Float64Array(3);
// Heliocentric position of 'mercury' ... 'neptune' or 'emb' (Earth-Moon barycentre), metres.
export function keplerPosition(id, jd, out) {
  if (CORR[id]) {
    const w = smooth((jd - (CW_LO - CFADE)) / CFADE) * smooth(((CW_HI + CFADE) - jd) / CFADE);
    if (w >= 1) return corrected(id, jd, out);
    if (w <= 0) return raw(id, jd, out, false);
    corrected(id, jd, out); raw(id, jd, tmpB, false);
    for (let k = 0; k < 3; k++) out[k] = w * out[k] + (1 - w) * tmpB[k];
    return out;
  }
  return raw(id, jd, out, jd >= T2A_START && jd <= T2A_END);
}
