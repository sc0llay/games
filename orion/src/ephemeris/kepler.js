export const isApproximate = (jd) => jd < RANGE_START || jd > RANGE_END;

const TWO_PI = Math.PI * 2;
// Solve Kepler's equation E - e sin E = M (radians) by Newton iteration.
export function solveKepler(M, e) {
  M = M % TWO_PI; if (M > Math.PI) M -= TWO_PI; else if (M < -Math.PI) M += TWO_PI;
  let E = e < 0.8 ? M + e * Math.sin(M) : Math.PI * Math.sign(M || 1);
  for (let i = 0; i < 30; i++) {
    const d = (E - e * Math.sin(E) - M) / (1 - e * Math.cos(E));
    E -= d;
    if (Math.abs(d) < 1e-13) break;
  }
  return E;
}

// Rotate perifocal (xp, yp) into the ecliptic frame; angles in radians. Writes metres-or-AU units unchanged.
export function perifocalToEcliptic(xp, yp, I, w, node, out) {
  const cw = Math.cos(w), sw = Math.sin(w), cO = Math.cos(node), sO = Math.sin(node), cI = Math.cos(I), sI = Math.sin(I);
  out[0] = (cw * cO - sw * sO * cI) * xp + (-sw * cO - cw * sO * cI) * yp;
  out[1] = (cw * sO + sw * cO * cI) * xp + (-sw * sO + cw * cO * cI) * yp;
  out[2] = sw * sI * xp + cw * sI * yp;
  return out;
}

const tmp = new Float64Array(3);
function raw(id, jd, out, useA) {
  const T = (jd - 2451545.0) / 36525;
  const el = (useA ? EL_2A : EL_2B)[id];
  const a = el[0] + el[1] * T, e = el[2] + el[3] * T, I = (el[4] + el[5] * T) * DEG;
  const L = el[6] + el[7] * T, vp = el[8] + el[9] * T, node = (el[10] + el[11] * T);
  let M = L - vp;
  if (!useA && el.length > 12 && !isApproximate(jd)) {
    M += el[12] * T * T + el[13] * Math.cos(el[15] * T * DEG) + el[14] * Math.sin(el[15] * T * DEG);
  }
  const E = solveKepler(M * DEG, e);
  const xp = a * (Math.cos(E) - e), yp = a * Math.sqrt(1 - e * e) * Math.sin(E);
  perifocalToEcliptic(xp, yp, I, (vp - node) * DEG, node * DEG, tmp);
  out[0] = tmp[0] * AU; out[1] = tmp[1] * AU; out[2] = tmp[2] * AU;
  return out;
}

